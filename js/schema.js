/* ============================================================================
   JSON-LD STRUCTURED DATA
   ============================================================================
   Builds the structured data from SITE_CONFIG, so the schema can never drift
   away from what the pages actually say. One `<script type="application/ld+json">`
   is injected per page, containing an `@graph`.

   RULES THIS MODULE ENFORCES — they are not style preferences, they are what
   keeps the markup inside Google's structured-data guidelines:

   1. Nothing is emitted that the configuration does not actually contain.
      An unset value is omitted, never guessed and never left as a visible
      placeholder string.

   2. `MovingCompany` is only emitted when a real street address exists.
      A LocalBusiness without a verifiable address is the single most common
      cause of a structured-data manual action on local sites.

   3. Neither `aggregateRating` nor `review` is ever emitted. Every review
      on this site is a review of this business published on this business's
      own site, which is what Google's guidelines mean by "self-serving" —
      and the ones republished from Google are third-party-aggregated on top
      of that. They are shown to readers; they are never marked up. See the
      long note on verifiedReviews() below.

   4. FAQPage is generated by reading the FAQ already rendered in the page.
      Google requires that the answer in the markup is visible on the page;
      generating it from the DOM makes that true automatically.

   HOW TO VALIDATE
   ---------------
   Deploy, then run the live URL through:
     - Google Rich Results Test — https://search.google.com/test/rich-results
     - Schema Markup Validator  — https://validator.schema.org/
   Both execute JavaScript, so they see what this module injects.
   See README.md § Validating structured data.
   ========================================================================== */

import {
  SITE_CONFIG, isSet, absoluteUrl,
  hasPublishableAddress, offeredServices,
} from './config.js';

const DAY_NAMES = {
  monday: 'Monday', tuesday: 'Tuesday', wednesday: 'Wednesday',
  thursday: 'Thursday', friday: 'Friday', saturday: 'Saturday', sunday: 'Sunday',
};

/** Strip keys whose value is null, undefined, '' or an empty array/object. */
function compact(obj) {
  const out = {};
  for (const [key, value] of Object.entries(obj)) {
    if (value === null || value === undefined || value === '') continue;
    if (Array.isArray(value) && value.length === 0) continue;
    if (typeof value === 'object' && !Array.isArray(value) && Object.keys(value).length === 0) continue;
    out[key] = value;
  }
  return out;
}

/** Only values that are genuinely configured. */
function val(value) {
  return isSet(value) ? value : null;
}

/* -------------------------------------------------------------------------
   Node builders
   ------------------------------------------------------------------------- */

function postalAddress() {
  const a = SITE_CONFIG.contact.address;

  /* `addressLocality` means the CITY, not the neighbourhood — Google matches
     a local business on it, so putting "Arya Nagar" there and leaving Kanpur
     out of the address altogether loses the one signal that matters most.
     The neighbourhood belongs on `streetAddress`, which is where schema.org
     expects a sub-locality to sit, so the two are joined here instead. */
  const street = [val(a.street), val(a.locality)].filter(Boolean).join(', ');

  const node = compact({
    '@type': 'PostalAddress',
    streetAddress: street || null,
    addressLocality: val(a.city) || val(a.locality),
    addressRegion: val(a.state),
    postalCode: val(a.postalCode),
    addressCountry: a.country || 'IN',
  });
  // An address with only a country in it is not an address.
  return Object.keys(node).length > 2 ? node : null;
}

function geoCoordinates() {
  const g = SITE_CONFIG.contact.geo;
  if (typeof g.latitude !== 'number' || typeof g.longitude !== 'number') return null;
  return { '@type': 'GeoCoordinates', latitude: g.latitude, longitude: g.longitude };
}

function openingHoursSpecification() {
  const hours = SITE_CONFIG.contact.openingHours || {};
  const out = [];
  for (const [day, range] of Object.entries(hours)) {
    if (!Array.isArray(range) || range.length !== 2) continue;   // closed
    out.push({
      '@type': 'OpeningHoursSpecification',
      dayOfWeek: 'https://schema.org/' + (DAY_NAMES[day] || day),
      opens: range[0],
      closes: range[1],
    });
  }
  return out;
}

/**
 * Social and directory profiles, as `sameAs`.
 *
 * `sameAs` is an identity claim, not a link list: it says "the thing at this
 * URL is this same business". That is exactly what is needed here, because
 * the domain is new and every existing listing is under the former trading
 * name, so without this the site reads as a different company that happens
 * to share a phone number.
 *
 * Only URLs that are actually set survive the filter, so an unclaimed or
 * unverified profile is omitted rather than guessed at. See the note in
 * config.js: a URL in here must have been opened and checked against the
 * business, because a wrong one is a false machine-readable statement.
 */
function sameAs() {
  const links = Object.values(SITE_CONFIG.social || {}).filter((u) => isSet(u));
  for (const url of Object.values(SITE_CONFIG.directories || {})) {
    if (isSet(url)) links.push(url);
  }
  const gbp = val(SITE_CONFIG.contact.googleBusinessProfile);
  if (gbp) links.push(gbp);
  return links;
}

/** Cities served, as `areaServed`. */
function areaServed() {
  return (SITE_CONFIG.serviceAreas || []).map((area) =>
    compact({
      '@type': 'City',
      name: val(area.city),
      containedInPlace: val(area.state)
        ? { '@type': 'State', name: area.state }
        : null,
    })
  ).filter((city) => city.name);
}

/**
 * Review nodes — and there are none, on purpose.
 *
 * This used to emit `Review` markup when `testimonials.source` was set to
 * 'firstParty', on the reasoning that reviews the business collected itself
 * are not aggregated from another platform. That reasoning was half right
 * and the conclusion was wrong.
 *
 * Google's review-snippet guidelines exclude SELF-SERVING reviews, and they
 * define the term by WHERE the review is published rather than by who
 * collected it: a review of a local business, on that business's own site,
 * is self-serving regardless of its provenance. Both halves of this site's
 * review content therefore fall outside it —
 *
 *   Google reviews republished here  self-serving AND aggregated from
 *                                    another platform: excluded twice.
 *   Testimonials collected directly  self-serving: excluded once.
 *
 * So the markup would not earn a star rating in search, and asking for one
 * anyway is how a site collects a structured-data manual action. The reviews
 * are still shown to readers in both sections; they are simply not claimed
 * as rich-result data.
 *
 * This function is kept rather than deleted so that the next person to go
 * looking for "why are there no stars in search" finds this note instead of
 * silence.
 */
function verifiedReviews() {
  return [];
}

/**
 * An aggregate rating is emitted only when it can be computed from reviews
 * the business actually holds. It is never typed in by hand.
 */
/* There is deliberately NO aggregateRating() any more.
   It used to average whatever reviews were in `testimonials.verified`. The
   moment that list holds a hand-picked selection of the best reviews — which
   is precisely what a testimonials section is — the average it produces is
   5.0, and the site starts publishing an overall rating the business has not
   earned. An overall rating may only come from the platform that holds every
   review, good and bad; see `testimonials.googleOverallRating` in config,
   which is displayed as text and never marked up. */

/* -------------------------------------------------------------------------
   The graph
   ------------------------------------------------------------------------- */

const ID = {
  org:     () => absoluteUrl('/#organization'),
  site:    () => absoluteUrl('/#website'),
  page:    (path) => absoluteUrl(path) + '#webpage',
  crumbs:  (path) => absoluteUrl(path) + '#breadcrumbs',
};

/**
 * Organization, or MovingCompany when a real address exists.
 * MovingCompany is a documented subtype of LocalBusiness on Schema.org.
 */
function organizationNode() {
  const addressable = hasPublishableAddress();
  const name = val(SITE_CONFIG.business.name);

  return compact({
    '@type': addressable ? 'MovingCompany' : 'Organization',
    '@id': ID.org(),
    name: name || undefined,
    /* The former trading name. Declaring it is how a search engine or an AI
       assistant learns that the forty years of listings, reviews and word of
       mouth under the old name belong to this same business. */
    alternateName: val(SITE_CONFIG.business.alternateName),
    legalName: val(SITE_CONFIG.business.legalName),
    url: absoluteUrl('/'),
    description: SITE_CONFIG.business.tagline,
    telephone: val(SITE_CONFIG.contact.phoneDial),
    email: val(SITE_CONFIG.contact.email),
    address: postalAddress(),
    geo: addressable ? geoCoordinates() : null,
    openingHoursSpecification: addressable ? openingHoursSpecification() : [],
    areaServed: areaServed(),
    sameAs: sameAs(),
    foundingDate: typeof SITE_CONFIG.business.foundingYear === 'number'
      ? String(SITE_CONFIG.business.foundingYear)
      : null,
    /* The proprietor. `founder` is the right property for a proprietorship:
       the business and the individual are the same legal person. Omitted
       entirely while unset — an unnamed Person node is worse than none. */
    founder: isSet(SITE_CONFIG.business.proprietor)
      ? compact({
        '@type': 'Person',
        name: SITE_CONFIG.business.proprietor,
        jobTitle: val(SITE_CONFIG.business.proprietorRole),
      })
      : null,
    /* Deliberately absent: priceRange, awards, numberOfEmployees — and
       aggregateRating, permanently. See the note above verifiedReviews(). */
    review: verifiedReviews(),
  });
}

function websiteNode() {
  return compact({
    '@type': 'WebSite',
    '@id': ID.site(),
    url: absoluteUrl('/'),
    name: val(SITE_CONFIG.business.name) || undefined,
    publisher: { '@id': ID.org() },
    inLanguage: 'en-IN',
  });
}

/**
 * The more specific WebPage subtype for this URL, or plain WebPage.
 *
 * Schema.org has subtypes for exactly the pages a service site has, and
 * using them costs nothing: an `AboutPage` tells a parser that this is the
 * page describing the organisation, which is useful to an answer engine
 * trying to summarise the business from the site.
 *
 * Matched on the path rather than on anything in the markup, so a page
 * cannot accidentally claim to be the contact page. Anything unrecognised
 * stays `WebPage` — a wrong subtype is worse than a general one.
 */
function pageType(path) {
  const p = String(path || '/').toLowerCase();
  if (p === '/about.html') return 'AboutPage';
  if (p === '/contact.html') return 'ContactPage';
  if (p === '/gallery.html') return 'CollectionPage';

  /* NOT FAQPage for /faq.html, deliberately. faqNode() below already emits
     a separate FAQPage node, built from the questions visible in the page.
     Typing the WebPage node as FAQPage too would put two FAQPage nodes with
     different @ids in one graph, which is exactly the duplicate, conflicting
     markup that gets a site a structured-data warning. One of them is
     enough, and the one with the questions in it is the useful one. */
  return 'WebPage';
}

function webPageNode({ path, title, description }) {
  return compact({
    '@type': pageType(path),
    '@id': ID.page(path),
    url: absoluteUrl(path),
    name: title || document.title,
    description: description
      || document.querySelector('meta[name="description"]')?.content
      || null,
    isPartOf: { '@id': ID.site() },
    about: { '@id': ID.org() },
    inLanguage: 'en-IN',
    breadcrumb: { '@id': ID.crumbs(path) },
  });
}

/** BreadcrumbList, built from the visible breadcrumb trail when present. */
function breadcrumbNode(path, trail) {
  const items = (trail && trail.length ? trail : readCrumbsFromDom());
  if (!items.length) return null;

  return {
    '@type': 'BreadcrumbList',
    '@id': ID.crumbs(path),
    itemListElement: items.map((item, index) => compact({
      '@type': 'ListItem',
      position: index + 1,
      name: item.name,
      item: item.url ? absoluteUrl(item.url) : null,
    })),
  };
}

function readCrumbsFromDom() {
  const nodes = Array.from(document.querySelectorAll('.crumbs li'));
  return nodes.map((li) => {
    const link = li.querySelector('a');
    return {
      name: (link ? link.textContent : li.textContent).trim(),
      url: link ? new URL(link.href).pathname : null,
    };
  }).filter((item) => item.name);
}

/** One Service node per offered service. */
function serviceNodes() {
  const cities = areaServed();
  return offeredServices().map((service) => compact({
    '@type': 'Service',
    '@id': absoluteUrl('/services/' + service.slug + '.html') + '#service',
    name: service.name,
    description: service.summary,
    serviceType: service.name,
    url: absoluteUrl('/services/' + service.slug + '.html'),
    provider: { '@id': ID.org() },
    areaServed: cities,
  }));
}

/**
 * FAQPage, read out of the page's own <details> elements so the markup and
 * the visible text cannot disagree. Returns null when the page has no FAQ.
 */
function faqNode() {
  const blocks = Array.from(document.querySelectorAll('[data-faq] details'));
  const entries = blocks.map((details) => {
    const question = details.querySelector('summary')?.textContent.trim();
    const answerEl = details.querySelector('.faq__body');
    const answer = answerEl ? answerEl.textContent.replace(/\s+/g, ' ').trim() : '';
    return { question, answer };
  }).filter((entry) => entry.question && entry.answer);

  if (entries.length < 2) return null;

  return {
    '@type': 'FAQPage',
    '@id': absoluteUrl(window.location.pathname) + '#faq',
    mainEntity: entries.map((entry) => ({
      '@type': 'Question',
      name: entry.question,
      acceptedAnswer: { '@type': 'Answer', text: entry.answer },
    })),
  };
}

/* -------------------------------------------------------------------------
   Public entry point
   ------------------------------------------------------------------------- */

/**
 * Build and inject the structured data for the current page.
 *
 * @param {object}  [options]
 * @param {string}  [options.path]        defaults to the current pathname
 * @param {boolean} [options.services]    include Service nodes (home + services pages)
 * @param {boolean} [options.faq]         include FAQPage if the page has an FAQ
 * @param {Array}   [options.breadcrumbs] [{ name, url }], else read from the DOM
 * @param {object}  [options.extra]       an additional node, e.g. Article
 */
export function injectSchema(options = {}) {
  // Without a business name there is nothing to describe, and publishing a
  // nameless LocalBusiness is worse than publishing none. Stay silent.
  if (!isSet(SITE_CONFIG.business.name)) {
    if (!/^(localhost|127\.0\.0\.1)$/.test(window.location.hostname)) return;
    // On localhost, say so in the console so the omission is not a mystery.
    console.info(
      '[schema] Structured data not injected: SITE_CONFIG.business.name is still ' +
      'PLACEHOLDER. Fill in js/config.js and it will appear automatically.'
    );
    return;
  }

  const path = options.path || window.location.pathname || '/';

  const graph = [
    organizationNode(),
    websiteNode(),
    webPageNode({ path, title: options.title, description: options.description }),
    breadcrumbNode(path, options.breadcrumbs),
    options.faq === false ? null : faqNode(),
    options.extra || null,
  ].filter(Boolean);

  if (options.services) graph.push(...serviceNodes());

  const payload = { '@context': 'https://schema.org', '@graph': graph };

  const script = document.createElement('script');
  script.type = 'application/ld+json';
  // textContent, not innerHTML: this is data, and it is never parsed as markup.
  script.textContent = JSON.stringify(payload);
  document.head.append(script);
}

/**
 * Print the generated JSON-LD to the console, formatted.
 * Handy if you would rather paste a static copy into the HTML — run
 * `window.__schema()` in the browser console on the page you want.
 *
 * LOCAL DEVELOPMENT ONLY. This attaches a global to `window`, and a debugging
 * hook is not something to ship: it is surface area that does nothing for a
 * visitor. Outside localhost the function returns without installing it, so
 * production pages carry no `__schema`.
 */
export function exposeSchemaDebug() {
  if (!/^(localhost|127\.0\.0\.1|\[::1\])$/.test(window.location.hostname)) return;

  window.__schema = () => {
    const node = document.querySelector('script[type="application/ld+json"]');
    if (!node) return '(no structured data on this page)';
    const json = JSON.stringify(JSON.parse(node.textContent), null, 2);
    console.log(json);
    return json;
  };
}

